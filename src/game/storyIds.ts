export function migrateLegacyMainNodeId(nodeId: string): string {
  if (nodeId === 'MENU') return nodeId;
  if (nodeId === 'fin_title' || /^fin_epi\d+$/.test(nodeId)) return TRUE_ENDING_START_NODE_ID;
  if (LEGACY_NORMAL_EPILOGUE_IDS.has(nodeId)) return NORMAL_ENDING_TITLE_NODE_ID;
  return LEGACY_MAIN_ID_MAP.get(nodeId) ?? nodeId;
}

export function migrateLegacyChoiceId(choiceId: string): string {
  const separator = choiceId.lastIndexOf('__');
  if (separator < 1) return choiceId;
  const nodeId = choiceId.slice(0, separator);
  const suffix = choiceId.slice(separator);
  const migratedNodeId = migrateLegacyMainNodeId(nodeId);
  return migratedNodeId === nodeId ? choiceId : `${migratedNodeId}${suffix}`;
}

export function isLegacyMainNodeId(nodeId: string): boolean {
  return LEGACY_MAIN_ID_MAP.has(nodeId)
    || nodeId === 'fin_title'
    || /^fin_epi\d+$/.test(nodeId)
    || LEGACY_NORMAL_EPILOGUE_IDS.has(nodeId);
}
