function createLegacyMainIdMap(): Map<string, string> {
  const normalizedIds = NORMALIZED_SECTIONS.flatMap(([prefix, count]) =>
    Array.from({ length: count }, (_, index) => `${prefix}-${String(index + 1).padStart(4, '0')}`),
  );
  return new Map(LEGACY_MAIN_NODE_IDS.map((legacyId, index) => [legacyId, normalizedIds[index]]));
}

